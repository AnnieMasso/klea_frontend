import type { ImageSourcePropType } from 'react-native';
import { getApiBaseUrl } from './api-config';

const localPhotos: Record<string, ImageSourcePropType> = {
  'maison.jpg': require('../assets/images/maison.jpg'),
  'icon.png': require('../assets/images/icon.png'),
  'favicon.png': require('../assets/images/favicon.png'),
};

function resolveNetworkImageUrl(value: string): string {
  const normalized = value.trim();
  if (!normalized) return normalized;

  // Keep device-local URIs untouched (camera roll, file cache, base64).
  if (/^(file|content|data):/i.test(normalized)) {
    return normalized;
  }

  const apiBaseUrl = getApiBaseUrl();
  if (!apiBaseUrl) {
    return normalized;
  }

  let apiOrigin = '';
  try {
    apiOrigin = new URL(apiBaseUrl).origin;
  } catch {
    return normalized;
  }

  // Rewrite localhost URLs generated by backend so phones can load them via LAN IP.
  if (/^https?:\/\/(localhost|127\.0\.0\.1)(:\d+)?/i.test(normalized)) {
    try {
      const source = new URL(normalized);
      return `${apiOrigin}${source.pathname}${source.search}${source.hash}`;
    } catch {
      return normalized;
    }
  }

  if (normalized.startsWith('/')) {
    return `${apiOrigin}${normalized}`;
  }

  if (/^https?:\/\//i.test(normalized)) {
    return normalized;
  }

  return `${apiOrigin}/${normalized.replace(/^\/+/, '')}`;
}

export function resolveImageSource(value: string): ImageSourcePropType {
  return localPhotos[value] ?? { uri: resolveNetworkImageUrl(value) };
}
